const expandableNodes = [...document.querySelectorAll(".route-expandable")];

function updateExpandableButton(button) {
  const expandable = button.closest(".route-expandable");
  const isOpen = expandable?.classList.contains("is-open") || false;
  const dictionary = translations[currentLanguage];
  const label = button.querySelector("span");
  const symbol = button.querySelector("i");

  if (label) label.textContent = dictionary[isOpen ? "expandClose" : "expandOpen"];
  if (symbol) symbol.textContent = isOpen ? "−" : "+";
  button.setAttribute("aria-expanded", String(isOpen));
}

expandableNodes.forEach((expandable, index) => {
  const heading = [...expandable.children].find(
    (child) => child.classList.contains("project-info") || child.classList.contains("section-heading")
  );

  if (!heading) return;

  const button = document.createElement("button");
  button.type = "button";
  button.className = "expand-toggle";
  button.setAttribute("aria-expanded", "false");
  button.innerHTML = '<span></span><i aria-hidden="true">+</i>';
  heading.insertAdjacentElement("afterend", button);

  const details = [...expandable.children].filter(
    (child) => child !== heading && child !== button
  );
  details.forEach((child) => child.setAttribute("data-expandable-content", `expandable-content-${index + 1}`));

  button.addEventListener("click", () => {
    expandable.classList.toggle("is-open");
    updateExpandableButton(button);
  });

  updateExpandableButton(button);
});

