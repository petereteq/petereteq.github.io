function currentSpaceFromHash() {
  const key = window.location.hash.replace("#", "");
  return routeAliases[key] || "home";
}

function showSpace({ scroll = false } = {}) {
  const space = currentSpaceFromHash();
  document.body.dataset.currentSpace = space;

  spaceNodes.forEach((node) => {
    node.hidden = node.dataset.space !== space;
  });

  routeLinks.forEach((link) => {
    const active = link.dataset.route === space;
    link.classList.toggle("is-active", active);
    if (active) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });

  if (scroll) {
    const targetId = window.location.hash.replace("#", "");
    const target = targetId ? document.getElementById(targetId) : null;
    const targetSpace = target?.dataset.space || target?.closest("[data-space]")?.dataset.space;
    if (target && targetSpace === space) {
      target.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
    } else {
      window.scrollTo({ top: 0, behavior: reduceMotion ? "auto" : "smooth" });
    }
  }
}

routeLinks.forEach((link) => {
  link.addEventListener("click", () => {
    if (link.dataset.route === currentSpaceFromHash()) showSpace({ scroll: true });
  });
});

