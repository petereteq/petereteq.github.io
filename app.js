let currentLanguage = "fr";

function saveLanguage(language) {
  try {
    localStorage.setItem("portfolio-language", language);
  } catch {
    // The language still changes when storage is unavailable.
  }
}

function loadLanguage() {
  try {
    return localStorage.getItem("portfolio-language");
  } catch {
    return null;
  }
}

function setLanguage(language, persist = true) {
  const dictionary = translations[language] || translations.fr;
  currentLanguage = translations[language] ? language : "fr";
  document.documentElement.lang = currentLanguage;
  document.title = dictionary.title;
  document.querySelector('meta[name="description"]').setAttribute("content", dictionary.description);

  textNodes.forEach((node) => {
    const value = dictionary[node.dataset.i18n];
    if (value) node.textContent = value;
  });

  ariaNodes.forEach((node) => {
    const value = dictionary[node.dataset.i18nAria];
    if (value) node.setAttribute("aria-label", value);
  });

  imageNodes.forEach((image) => {
    const value = dictionary[image.dataset.alt];
    if (value) image.alt = value;
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === currentLanguage));
  });

  document.querySelectorAll(".expand-toggle").forEach(updateExpandableButton);

  if (persist) saveLanguage(currentLanguage);
}

